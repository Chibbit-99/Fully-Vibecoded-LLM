#!/usr/bin/env python3
"""Rewrite the README's training-results section from model/meta.json.

The training workflow calls this after publishing, so the README always shows
the real numbers of the model that is actually committed — no hand-editing and
no drift between the docs and the weights.

    python scripts/update_readme.py

Everything between the HTML markers is replaced:

    <!-- TRAINING_METRICS -->
    ...generated...
    <!-- /TRAINING_METRICS -->
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
META = ROOT / "model" / "meta.json"

START = "<!-- TRAINING_METRICS -->"
END = "<!-- /TRAINING_METRICS -->"


def human(n) -> str:
    try:
        n = float(n)
    except (TypeError, ValueError):
        return "—"
    if n >= 1e9:
        return f"{n/1e9:.2f}B"
    if n >= 1e6:
        return f"{n/1e6:.2f}M"
    if n >= 1e3:
        return f"{n/1e3:.1f}k"
    return f"{n:,.0f}"


def render(meta: dict) -> str:
    cfg = meta.get("config", {})
    steps = meta.get("steps")
    val = meta.get("val_loss")
    bpc = meta.get("bits_per_byte")
    params = meta.get("params")
    tokens = meta.get("tokens_seen")
    secs = meta.get("train_seconds")
    history = meta.get("history") or []

    minutes = f"{secs/60:.0f} min" if isinstance(secs, (int, float)) and secs else "—"
    tps = f"{tokens/secs:,.0f} tok/s" if tokens and secs else ""
    token_count = history[-1].get("step", 0) if False else None
    has_curve = (ROOT / "model" / "loss_curve.svg").exists()
    val_pts = [h for h in history if "val_loss" in h]
    first_val = val_pts[0]["val_loss"] if val_pts else None
    last_val = val_pts[-1]["val_loss"] if val_pts else None

    lines = [
        START,
        "## Training results",
        "",
        f"> Generated by `scripts/update_readme.py` from `model/meta.json` — the numbers below",
        f"> describe the exact weights committed in `model/weights.json`.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Parameters | **{human(params)}** ({params:,}) |" if params else "| Parameters | — |",
        f"| Architecture | {cfg.get('n_layer','?')} layers · {cfg.get('n_head','?')} heads · d_model {cfg.get('n_embd','?')} · context {cfg.get('block_size','?')} |",
        f"| Vocabulary | {cfg.get('vocab_size','?')} byte-BPE tokens |",
        f"| Optimiser steps | **{steps:,}** |" if steps else "| Optimiser steps | — |",
        f"| Tokens seen | {human(tokens)} ({tokens:,}) |" if tokens else "| Tokens seen | see *steps × batch × context* below |",
        f"| Validation loss | **{val:.4f}** nats/token |" if isinstance(val, (int, float)) else "| Validation loss | — |",
        f"| Bits per byte | **{bpc:.3f}** (8.0 = random bytes) |" if isinstance(bpc, (int, float)) else "| Bits per byte | — (computed at the end of training) |",
        f"| Training time | {minutes} on CPU {tps} |" if minutes != "—" else "| Training time | local GPU-less run (see `runs/main/train.log`) |",
        f"| Loss trajectory | {first_val:.3f} → {last_val:.3f} |" if first_val and last_val else "| Loss trajectory | — |",
    ]

    if has_curve:
        lines += [
            "",
            '<p align="center"><img src="model/loss_curve.svg" alt="training and validation loss" width="680"></p>',
            '<p align="center"><sub>train loss in blue, validation loss in green — rendered by scripts/train.py</sub></p>',
        ]

    samples = ROOT / "model" / "samples.txt"
    if samples.exists():
        text = samples.read_text()
        # first sample block: everything between the first PROMPT line and the next '='
        blocks = text.split("=" * 70)
        snippet = ""
        for b in blocks:
            if "PROMPT:" in b:
                body = b.split("-" * 70, 1)
                if len(body) == 2:
                    snippet = body[1].strip()[:420]
                    break
        if snippet:
            lines += [
                "",
                "<details>",
                "<summary><b>Sample generation</b> (from the committed weights)</summary>",
                "",
                "```",
                snippet,
                "```",
                "",
                "</details>",
            ]

    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    if not META.exists():
        print(f"{META} not found — nothing to do", file=sys.stderr)
        return 1
    meta = json.loads(META.read_text())
    readme = README.read_text()

    block = render(meta)
    if START in readme and END in readme:
        head = readme.split(START)[0]
        tail = readme.split(END, 1)[1]
        new = head + block + tail
    else:
        # first run: insert before the "Quick start" heading
        marker = "## Quick start"
        new = readme.replace(marker, block + "\n\n" + marker, 1)

    README.write_text(new)
    print(f"updated {README} from {META} (steps={meta.get('steps')}, val={meta.get('val_loss')})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
